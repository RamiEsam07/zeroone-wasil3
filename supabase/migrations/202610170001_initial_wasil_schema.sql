create table public.stores (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete restrict,
  category_id uuid references public.categories(id) on delete set null,
  name_ar text not null,
  name_en text,
  description text,
  phone text,
  image_url text,
  address_text text,
  latitude double precision,
  longitude double precision,
  is_open boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint stores_latitude_range check (latitude is null or latitude between -90 and 90),
  constraint stores_longitude_range check (longitude is null or longitude between -180 and 180)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  name_ar text not null,
  name_en text,
  description text,
  image_url text,
  category text not null default '',
  price numeric(12,2) not null check (price >= 0),
  currency text not null default 'SDG',
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  is_available boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.addresses (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.profiles(id) on delete cascade,
  label text not null default 'المنزل',
  address_text text not null,
  city text not null default 'KHARTOUM' check (city in ('KHARTOUM', 'OMDURMAN', 'BAHRI', 'PORT_SUDAN', 'WAD_MADANI')),
  area text not null default '',
  street text not null default '',
  building_number text not null default '',
  floor_or_apartment text not null default '',
  landmark text not null default '',
  recipient_name text not null default '',
  recipient_phone text not null default '',
  latitude double precision,
  longitude double precision,
  details text,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  constraint addresses_latitude_range check (latitude is null or latitude between -90 and 90),
  constraint addresses_longitude_range check (longitude is null or longitude between -180 and 180)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid not null references public.profiles(id) on delete restrict,
  store_id uuid not null references public.stores(id) on delete restrict,
  driver_id uuid references public.profiles(id) on delete set null,
  address_id uuid references public.addresses(id) on delete set null,
  status public.wasil_order_status not null default 'placed',
  payment_method public.wasil_payment_method not null default 'cash_on_delivery',
  payment_status public.wasil_payment_status not null default 'pending',
  currency text not null default 'SDG',
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  service_fee numeric(12,2) not null default 250 check (service_fee >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  customer_notes text,
  idempotency_key uuid,
  customer_name_snapshot text not null default '',
  customer_phone_snapshot text not null default '',
  store_name_snapshot text not null default '',
  store_phone_snapshot text,
  store_image_snapshot text,
  delivery_address_snapshot text not null default '',
  recipient_name_snapshot text,
  recipient_phone_snapshot text,
  cancellation_reason text,
  driver_release_reason text,
  placed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  delivered_at timestamptz,
  constraint orders_customer_idempotency_key_unique unique (customer_id, idempotency_key)
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name_snapshot text not null,
  special_instructions text not null default '',
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) generated always as (unit_price * quantity) stored
);

create table public.driver_profiles (
  profile_id uuid primary key references public.profiles(id) on delete cascade,
  vehicle_type text not null default 'motorcycle' check (vehicle_type in ('motorcycle', 'car', 'bicycle', 'other')),
  is_available boolean not null default false,
  latitude double precision,
  longitude double precision,
  last_location_at timestamptz,
  commission_balance numeric(12,2) not null default 0 check (commission_balance >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint driver_latitude_range check (latitude is null or latitude between -90 and 90),
  constraint driver_longitude_range check (longitude is null or longitude between -180 and 180)
);

create index stores_category_active_idx on public.stores(category_id, is_active, is_open);
create index products_store_available_idx on public.products(store_id, is_available);
create index addresses_customer_idx on public.addresses(customer_id);
create index orders_customer_created_idx on public.orders(customer_id, placed_at desc);
create index orders_store_status_idx on public.orders(store_id, status, placed_at desc);
create index orders_driver_status_idx on public.orders(driver_id, status);
create index driver_profiles_available_idx on public.driver_profiles(is_available);

-- Create a customer profile automatically after successful Supabase Auth sign-up.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, role, phone, full_name)
  values (
    new.id,
    'customer',
    new.phone,
    nullif(new.raw_user_meta_data ->> 'full_name', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_wasil on auth.users;
create trigger on_auth_user_created_wasil
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at before update on public.profiles
for each row execute procedure public.set_updated_at();
create trigger stores_set_updated_at before update on public.stores
for each row execute procedure public.set_updated_at();
create trigger products_set_updated_at before update on public.products
for each row execute procedure public.set_updated_at();
create trigger orders_set_updated_at before update on public.orders
for each row execute procedure public.set_updated_at();
create trigger driver_profiles_set_updated_at before update on public.driver_profiles
for each row execute procedure public.set_updated_at();

-- Helpers avoid recursive RLS lookups into profiles.
create or replace function public.current_wasil_role()
returns public.wasil_role
language sql
stable
security definer
set search_path = ''
as $$
  select p.role from public.profiles p where p.id = (select auth.uid())
$$;

-- True only when the signed-in user has an active profile. Sensitive RPCs
-- must check this separately from role membership.
create or replace function public.current_wasil_account_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select p.is_active from public.profiles p where p.id = (select auth.uid())),
    false
  )
$$;

create or replace function public.is_wasil_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.current_wasil_account_active()
     and coalesce(public.current_wasil_role() = 'admin'::public.wasil_role, false)
$$;

create or replace function public.owns_wasil_store(target_store_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.stores s
    where s.id = target_store_id
      and s.owner_id = (select auth.uid())
      and public.current_wasil_account_active()
  )
$$;

-- Limit helper execution to the roles whose RLS policies need these functions.
-- Public catalog policies evaluate is_wasil_admin/owns_wasil_store for anon users,
-- but those helpers return false for anonymous requests without an auth.uid().
revoke all on function public.current_wasil_role() from public, anon;
grant execute on function public.current_wasil_role() to authenticated;
revoke all on function public.current_wasil_account_active() from public, anon;
grant execute on function public.current_wasil_account_active() to authenticated;
revoke all on function public.is_wasil_admin() from public, anon;
grant execute on function public.is_wasil_admin() to anon, authenticated;
revoke all on function public.owns_wasil_store(uuid) from public, anon;
grant execute on function public.owns_wasil_store(uuid) to anon, authenticated;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.stores enable row level security;
alter table public.products enable row level security;
alter table public.addresses enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.driver_profiles enable row level security;

-- Profiles: user may read their own record; role is not exposed as a client-editable field.
create policy "profiles_read_self_or_admin" on public.profiles
for select to authenticated
using (id = (select auth.uid()) or public.is_wasil_admin());

create policy "profiles_update_self_basic" on public.profiles
for update to authenticated
using (id = (select auth.uid()) and public.current_wasil_account_active())
with check (
  id = (select auth.uid())
  and role = public.current_wasil_role()
  and public.current_wasil_account_active()
);

-- Public catalog is read-only to anonymous and authenticated users.
create policy "categories_read_active" on public.categories
for select to anon, authenticated
using (is_active or public.is_wasil_admin());

create policy "stores_read_active" on public.stores
for select to anon, authenticated
using ((is_active and is_open) or public.owns_wasil_store(id) or public.is_wasil_admin());

create policy "stores_read_assigned_driver" on public.stores
for select to authenticated
using (
  public.current_wasil_role() = 'driver'::public.wasil_role
  and public.current_wasil_account_active()
  and exists (
    select 1 from public.orders o
    where o.store_id = id and o.driver_id = (select auth.uid())
  )
);

create policy "stores_owner_insert" on public.stores
for insert to authenticated
with check (
  owner_id = (select auth.uid())
  and public.current_wasil_role() = 'merchant'
  and public.current_wasil_account_active()
);

create policy "stores_owner_update" on public.stores
for update to authenticated
using (
  (owner_id = (select auth.uid()) and public.current_wasil_account_active())
  or public.is_wasil_admin()
)
with check (
  (owner_id = (select auth.uid()) and public.current_wasil_account_active())
  or public.is_wasil_admin()
);

create policy "products_read_available" on public.products
for select to anon, authenticated
using (
  (is_active and is_available and exists (
    select 1 from public.stores s where s.id = store_id and s.is_active and s.is_open
  ))
  or public.owns_wasil_store(store_id)
  or public.is_wasil_admin()
);

create policy "products_owner_insert" on public.products
for insert to authenticated
with check (
  public.owns_wasil_store(store_id)
  and public.current_wasil_role() = 'merchant'
  and public.current_wasil_account_active()
);

create policy "products_owner_update" on public.products
for update to authenticated
using (public.owns_wasil_store(store_id) or public.is_wasil_admin())
with check (public.owns_wasil_store(store_id) or public.is_wasil_admin());

create policy "products_owner_delete" on public.products
for delete to authenticated
using (public.owns_wasil_store(store_id) or public.is_wasil_admin());

-- Addresses are private to their owner.
create policy "addresses_owner_all" on public.addresses
for all to authenticated
using (
  (
    customer_id = (select auth.uid())
    and public.current_wasil_role() = 'customer'::public.wasil_role
    and public.current_wasil_account_active()
  )
  or public.is_wasil_admin()
)
with check (
  (
    customer_id = (select auth.uid())
    and public.current_wasil_role() = 'customer'::public.wasil_role
    and public.current_wasil_account_active()
  )
  or public.is_wasil_admin()
);

-- Customers can create/read their own orders. Merchants see orders for their own stores.
create policy "addresses_read_assigned_driver" on public.addresses
for select to authenticated
using (
  public.current_wasil_role() = 'driver'::public.wasil_role
  and public.current_wasil_account_active()
  and exists (
    select 1 from public.orders o
    where o.address_id = id and o.driver_id = (select auth.uid())
  )
);

create policy "orders_read_participants" on public.orders
for select to authenticated
using (
  (
    public.current_wasil_account_active()
    and (
      customer_id = (select auth.uid())
      or driver_id = (select auth.uid())
      or public.owns_wasil_store(store_id)
    )
  )
  or public.is_wasil_admin()
);

-- Direct client writes to orders and order_items are intentionally disabled.
-- A trusted RPC must calculate authoritative prices from products, validate address/store,
-- decrement stock transactionally, and insert the order and items atomically.
-- Status changes/driver assignment must also use server-validated RPCs.

create policy "order_items_read_participants" on public.order_items
for select to authenticated
using (
  public.is_wasil_admin()
  or (
    public.current_wasil_account_active()
    and exists (
      select 1 from public.orders o
      where o.id = order_id
        and (
          o.customer_id = (select auth.uid())
          or o.driver_id = (select auth.uid())
          or public.owns_wasil_store(o.store_id)
        )
    )
  )
);

-- Drivers may read/update their own driver profile. Admins can manage all.
create policy "driver_profile_read_self_or_admin" on public.driver_profiles
for select to authenticated
using ((profile_id = (select auth.uid()) and public.current_wasil_account_active()) or public.is_wasil_admin());

create policy "driver_profile_insert_self" on public.driver_profiles
for insert to authenticated
with check (
  profile_id = (select auth.uid())
  and public.current_wasil_role() = 'driver'
  and public.current_wasil_account_active()
);

create policy "driver_profile_update_self" on public.driver_profiles
for update to authenticated
using (
  profile_id = (select auth.uid())
  and public.current_wasil_role() = 'driver'
  and public.current_wasil_account_active()
)
with check (
  profile_id = (select auth.uid())
  and public.current_wasil_role() = 'driver'
  and public.current_wasil_account_active()
);

-- Grant only the table operations used by the policies; RLS still controls row access.
grant select on public.categories, public.stores, public.products to anon, authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert, update, delete on public.addresses to authenticated;
grant select, insert, update on public.driver_profiles to authenticated;
grant insert, update, delete on public.stores, public.products to authenticated;

commit;

