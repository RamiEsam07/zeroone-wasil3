-- WASIL initial shared schema for Supabase
-- Review this migration before running it in the Supabase SQL Editor.
-- Safe defaults: roles are not user-editable; RLS is enabled on every public table.
-- Never use a service_role/secret key in a mobile app.

begin;

create extension if not exists pgcrypto;

create type public.wasil_role as enum ('customer', 'merchant', 'driver', 'admin');
create type public.wasil_order_status as enum (
  'placed',
  'confirmed',
  'preparing',
  'ready_for_pickup',
  'driver_assigned',
  'picked_up',
  'on_the_way',
  'delivered',
  'cancelled'
);
create type public.wasil_payment_method as enum ('cash_on_delivery', 'electronic');
create type public.wasil_payment_status as enum ('pending', 'paid', 'failed', 'refunded');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.wasil_role not null default 'customer',
  full_name text,
  phone text,
  avatar_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  name_ar text not null,
  name_en text,
  slug text not null unique,
  icon_url text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

